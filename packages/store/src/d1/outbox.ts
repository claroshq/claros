/**
 * SQLite / D1: outbox inserts for state changes (see ../areas/shared-outbox.ts).
 *
 * Reads the product's enabled endpoints first (d1OutboxEndpoints), then
 * builds INSERT ... SELECT statements for the caller to put in the same
 * db.batch() as the state change, so both commit or neither does. With
 * `afterChange`, a statement inserts only when the statement right before
 * it in the batch changed a row (SQLite changes()): a compare-and-swap
 * that lost a race writes no event. An endpoint added or removed between
 * the read and the batch takes effect from the next event on.
 */
import { and, eq, sql, type SQL } from "drizzle-orm";
import { webhookEndpoints, webhookOutbox } from "@claros/db/schema-sqlite";
import type { D1Db } from "./db.js";
import type { OutboxEntry } from "../areas/shared-outbox.js";
import { pendingApprovalBatch, endpointBatchMinutes } from "@claros/core";

export type OutboxEndpoints = ReadonlyArray<{ id: string; events: unknown; config?: unknown }>;

/** Endpoints of a product, read before building a batch. */
export async function d1OutboxEndpoints(db: D1Db, tenantId: string, entries: readonly OutboxEntry[] | undefined): Promise<OutboxEndpoints> {
  if (!entries || entries.length === 0) return [];
  return db
    .select({ id: webhookEndpoints.id, events: webhookEndpoints.events, config: webhookEndpoints.config })
    .from(webhookEndpoints)
    .where(and(eq(webhookEndpoints.tenantId, tenantId), eq(webhookEndpoints.enabled, true)));
}

/** 8 bound parameters per row: 12 rows keep a statement under D1's limit of 100. */
const ROWS_PER_STATEMENT = 12;

/** Insert statements (zero or more) for the entries that endpoints subscribe to. */
export function d1OutboxInserts(
  db: D1Db,
  tenantId: string,
  endpoints: OutboxEndpoints,
  entries: readonly OutboxEntry[] | undefined,
  now: Date,
  opts: { afterChange?: boolean } = {},
) {
  if (!entries || entries.length === 0 || endpoints.length === 0) return [];
  const rows: SQL[] = [];
  for (const entry of entries) {
    for (const ep of endpoints) {
      const events = Array.isArray(ep.events) ? (ep.events as string[]) : [];
      if (!events.includes(entry.event)) continue;
      const batch = entry.batched ? pendingApprovalBatch(now, endpointBatchMinutes(ep.config)) : null;
      const deliverAt = batch?.deliverAt ?? entry.deliverAt ?? now;
      const dedupKey = batch?.dedupKey ?? entry.dedupKey ?? null;
      rows.push(
        sql`(${crypto.randomUUID()}, ${tenantId}, ${ep.id}, ${entry.event}, ${JSON.stringify(entry.payload)}, 'pending', 0, ${deliverAt.getTime()}, NULL, ${dedupKey}, ${now.getTime()}, NULL)`,
      );
    }
  }
  const guard = opts.afterChange ? sql`changes() > 0` : sql`1`;
  const statements = [];
  for (let i = 0; i < rows.length; i += ROWS_PER_STATEMENT) {
    const values = sql.join(rows.slice(i, i + ROWS_PER_STATEMENT), sql`, `);
    statements.push(
      db
        .insert(webhookOutbox)
        .select(sql`SELECT * FROM (VALUES ${values}) WHERE ${guard}`)
        .onConflictDoNothing(),
    );
  }
  return statements;
}

/** A uuid v4 generated by SQLite (for rows built by INSERT ... SELECT). */
const SQL_UUID = sql.raw(
  "lower(hex(randomblob(4))) || '-' || lower(hex(randomblob(2))) || '-4' || substr(lower(hex(randomblob(2))), 2) || '-' || " +
    "substr('89ab', 1 + (abs(random()) % 4), 1) || substr(lower(hex(randomblob(2))), 2) || '-' || lower(hex(randomblob(6)))",
);

/**
 * One outbox row per (source row, subscribed endpoint), built in SQL from
 * rows the batch just changed: `from` is a table with alias `src`, `where`
 * the condition picking the rows, `payload` a json_object(...) expression
 * over them. Null when no endpoint subscribes to the event.
 */
export function d1OutboxFromSelect(
  db: D1Db,
  tenantId: string,
  endpoints: OutboxEndpoints,
  event: string,
  from: SQL,
  where: SQL,
  payload: SQL,
  now: Date,
) {
  const ids = endpoints
    .filter((ep) => Array.isArray(ep.events) && (ep.events as string[]).includes(event))
    .map((ep) => sql`(${ep.id})`);
  if (ids.length === 0) return null;
  const ms = now.getTime();
  return db.insert(webhookOutbox).select(sql`
    SELECT ${SQL_UUID}, ${tenantId}, eps.column1, ${event}, ${payload}, 'pending', 0, ${ms}, NULL, NULL, ${ms}, NULL
    FROM ${from}
    CROSS JOIN (VALUES ${sql.join(ids, sql`, `)}) AS eps
    WHERE ${where}
  `);
}
