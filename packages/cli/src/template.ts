/**
 * The wrangler.jsonc template for a deployed instance.
 *
 * Mirrors the development template apps/worker/wrangler.jsonc (bindings,
 * queue settings, cron, assets rules); a test keeps the two in step. The
 * deploy fills in the resource names and ids, the routes and BASE_URL.
 */
import { createHash } from "node:crypto";
import type { Assets } from "./assets.js";
import type { InstanceState } from "./state.js";
import { D1_BINDING } from "./wrangler.js";

/** Same value as apps/worker/wrangler.jsonc. */
export const COMPATIBILITY_DATE = "2026-11-20";

/** Paths that always reach the Worker before Static Assets (apps/worker/wrangler.jsonc). */
export const RUN_WORKER_FIRST = [
  "/health",
  "/version",
  "/auth",
  "/auth/*",
  "/invite",
  "/invite/*",
  "/unsubscribe",
  "/unsubscribe/*",
  "/webhooks/*",
  "/v1",
  "/v1/*",
];

export const CRON = "*/5 * * * *";

/**
 * Cloudflare Email Service sending binding, read by the Worker as env.EMAIL
 * (apps/worker/src/transports.ts) for `cloudflare` transports.
 *
 * https://developers.cloudflare.com/email-service/configuration/send-bindings/
 * A binding with only `name` and no restriction attribute "can send to any
 * recipient"; the sender must belong to a domain onboarded to Email Service,
 * which Cloudflare checks at send time (E_SENDER_DOMAIN_NOT_AVAILABLE), not
 * at deploy. So every deployed instance gets it: an instance without an
 * onboarded domain or without a `cloudflare` transport never calls it, and
 * Claros only routes transactional topics to `cloudflare` transports.
 */
export const SEND_EMAIL_BINDING = "EMAIL";

export interface WranglerRoute {
  pattern: string;
  custom_domain: true;
}

export interface GeneratedConfig {
  name: string;
  main: string;
  account_id: string;
  compatibility_date: string;
  compatibility_flags: string[];
  workers_dev: boolean;
  routes: WranglerRoute[];
  d1_databases: Array<{ binding: string; database_name: string; database_id: string; migrations_dir: string }>;
  queues: {
    producers: Array<{ binding: string; queue: string }>;
    consumers: Array<Record<string, unknown>>;
  };
  triggers: { crons: string[] };
  send_email: Array<{ name: string }>;
  assets: Record<string, unknown>;
  vars: Record<string, string>;
  observability: { enabled: boolean };
}

export interface TemplateInput {
  state: InstanceState;
  assets: Assets;
  /** Product public hosts (tenants.public_host) that get a custom domain route. */
  productHosts: string[];
  /** Leave the custom domain routes out (first deploy that only creates the Worker). */
  withoutRoutes?: boolean;
}

/** Hosts that get a custom domain route: the instance domain, then product hosts (sorted, unique). */
export function routeHosts(state: InstanceState, productHosts: string[]): string[] {
  const hosts: string[] = [];
  if (state.customDomain && state.host) hosts.push(state.host);
  for (const h of [...productHosts].sort()) if (!hosts.includes(h)) hosts.push(h);
  return hosts;
}

export function generateConfig(input: TemplateInput): GeneratedConfig {
  const { state, assets } = input;
  if (!state.d1Id) throw new Error("internal: D1 database id unknown");
  const routes: WranglerRoute[] = input.withoutRoutes
    ? []
    : routeHosts(state, input.productHosts).map((pattern) => ({ pattern, custom_domain: true }));
  const vars: Record<string, string> = { CLAROS_VERSION: assets.version };
  // Without a known host BASE_URL stays unset: the Worker then refuses to
  // send in production instead of baking a wrong URL into mail.
  if (state.host) vars.BASE_URL = `https://${state.host}`;
  return {
    name: state.workerName,
    main: assets.workerMain,
    account_id: state.accountId,
    compatibility_date: COMPATIBILITY_DATE,
    compatibility_flags: ["nodejs_compat"],
    workers_dev: !state.customDomain,
    routes,
    d1_databases: [
      {
        binding: D1_BINDING,
        database_name: state.d1Name,
        database_id: state.d1Id,
        migrations_dir: assets.migrationsDir,
      },
    ],
    queues: {
      producers: [{ binding: "JOBS", queue: state.queues.jobs }],
      consumers: [
        {
          queue: state.queues.jobs,
          max_batch_size: 10,
          max_batch_timeout: 5,
          max_retries: 3,
          dead_letter_queue: state.queues.dlq,
        },
        { queue: state.queues.dlq, max_batch_size: 10, max_batch_timeout: 30 },
      ],
    },
    triggers: { crons: [CRON] },
    send_email: [{ name: SEND_EMAIL_BINDING }],
    assets: {
      directory: assets.dashboardDir,
      binding: "ASSETS",
      not_found_handling: "none",
      html_handling: "none",
      run_worker_first: RUN_WORKER_FIRST,
    },
    vars,
    observability: { enabled: true },
  };
}

/** The file content: a short header comment, then the configuration as JSON. */
export function renderConfig(config: GeneratedConfig): string {
  return [
    "// Generated by `claros deploy`. Changes here are overwritten on the next deploy.",
    "// Secrets (ENCRYPTION_KEY, UNSUBSCRIBE_SIGNING_KEY) are set on the Worker, not here.",
    JSON.stringify(config, null, 2),
    "",
  ].join("\n");
}

/**
 * Stable hash of a configuration (a second deploy with the same hash is
 * skipped). Local paths are left out: the same version run from another
 * npx cache directory deploys the same Worker. CLAROS_VERSION is in vars.
 */
export function configHash(config: GeneratedConfig): string {
  const portable = {
    ...config,
    main: "",
    assets: { ...config.assets, directory: "" },
    d1_databases: config.d1_databases.map((d) => ({ ...d, migrations_dir: "" })),
  };
  return createHash("sha256").update(JSON.stringify(portable)).digest("hex").slice(0, 16);
}
