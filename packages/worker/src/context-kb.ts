/**
 * KB context builder - KB search half of Phase 3 exit criteria.
 *
 * This is NOT task 23 (auto-crawl). It is the similarity search path that
 * wires existing embeddings into the content generation context packet.
 * Task numbering: this work sits between task 22 (embeddings) and task 23
 * (auto-crawl) and is referenced in §11 Phase 3 exit criteria.
 *
 * [impl] Query text: the step's brain_instruction concatenated with the
 * action_type, separated by ": ". The action_type is always present (defaults
 * to "nurture_value" in the assembler), so the query is never empty when
 * brain_instruction is absent. Contact behavior (event names, lifecycle state)
 * is deliberately excluded: event names are a product-specific vocabulary that
 * does not share a semantic space with knowledge base prose. Example: an event
 * named "project_created" will not match a KB entry about "billing FAQ"
 * meaningfully. The brain_instruction + action_type describes what the email
 * step is about, which IS the same semantic space as the KB entries.
 *
 * [impl] Explicit kb_ref beats search. If the compiled plan step carries a
 * kb_ref, that entry is always included (fetched by title, case-sensitive,
 * tenant-scoped, embedded or not). The remaining slots (up to KB_MAX_RESULTS
 * total) are filled by semantic search, or by word matching when no
 * embedding provider is configured or the query embedding fails. If the
 * kb_ref entry is not found, it is omitted and search fills all slots.
 *
 * [impl] Retrieval parameters - unvalidated starting values, recorded here
 * for calibration:
 *   KB_MAX_RESULTS = 3  (max entries returned; start conservatively)
 *   KB_SIMILARITY_FLOOR = 0.70  (cosine similarity threshold 0..1; unvalidated)
 *
 * Both are named constants so they can be adjusted without touching logic.
 * Similarity scores of retrieved and rejected entries are logged at debug
 * level so they can be monitored against real data and these constants
 * calibrated later.
 *
 * [impl] Model consistency: the query vector MUST be generated by the same
 * model used to generate the stored entry vectors. If a tenant changes their
 * embedding provider in Settings, Embeddings (PUT/DELETE
 * /v1/settings/embeddings), stored vectors are dropped and re-embedded when
 * the base URL, model or dimensions change. A change of the legacy
 * llm_configs embedding_model is not detected; saving the provider in
 * Settings, Embeddings re-embeds everything with one model.
 *
 * [impl] Embedding API call cost: every message that reaches content
 * generation now incurs one embedding API call for the KB query. This call
 * uses the same provider (baseUrl + apiKey + embeddingModel) as the entry
 * indexing. The query text (brain_instruction + action_type) is the same for
 * all contacts on the same flow step, which means the query vector is
 * identical across contacts. At MVP scale (small tenant, few contacts per
 * step) this is immaterial. At scale, a per-step query cache keyed on
 * (tenant_id, flow_id, step_order, embedding_model) would eliminate redundant
 * API calls entirely. See docs/BACKLOG.md "KB query vector cache" for the
 * tracking item. No cache is built here.
 */
import type { NodePgDatabase } from "drizzle-orm/node-postgres";
import { storeFor } from "@claros/store";
import {
  resolveEmbeddingProvider,
  callEmbedding,
  EmbeddingPermanentError,
} from "./embedding-client.js";

// ---------------------------------------------------------------------------
// Types
// ---------------------------------------------------------------------------

type Db = NodePgDatabase<Record<string, never>>;

// ---------------------------------------------------------------------------
// Constants
// ---------------------------------------------------------------------------

/**
 * Maximum number of KB entries to include in the context packet.
 * Unvalidated starting value - calibrate against real data.
 * Kept low to limit token budget pressure on the context.
 */
export const KB_MAX_RESULTS = 3;

/**
 * Minimum cosine similarity score for an entry to be included.
 * Range 0..1 (0 = orthogonal, 1 = identical). 0.70 is a conservative start.
 * Entries at or above this threshold are "relevant"; below are "weak matches".
 * Calibrate by observing logged similarity scores against real knowledge bases.
 */
export const KB_SIMILARITY_FLOOR = 0.70;

/**
 * Most active entries the keyword fallback reads per message. Knowledge bases
 * past this size get word matching over their oldest entries only; they
 * should configure an embedding provider.
 */
export const KB_KEYWORD_SCAN_LIMIT = 500;

/**
 * Minimum number of distinct query words (stop words removed) an entry's
 * title and content must contain to be included by the keyword fallback.
 * Unvalidated starting value, like KB_SIMILARITY_FLOOR.
 */
export const KB_KEYWORD_MIN_SHARED_WORDS = 2;

// ---------------------------------------------------------------------------
// buildKbContextSection
// ---------------------------------------------------------------------------

/**
 * Build the kb_context string for the draft prompt.
 *
 * Steps:
 * 1. If the step carries an explicit kb_ref, fetch that entry by title
 *    (embedded or not: the reference is explicit).
 * 2. Fill the remaining slots by semantic search when an embedding provider
 *    resolves (embed the query, cosine similarity over embedded entries).
 * 3. Otherwise, or when the query embedding or the search fails, fill them by
 *    word matching: entries sharing at least KB_KEYWORD_MIN_SHARED_WORDS
 *    words with the query, most shared first, ties to the oldest.
 * 4. Format and return the combined context string.
 *
 * Graceful degradation: no entries found = undefined (no section emitted
 * rather than an empty "KNOWLEDGE BASE CONTEXT:" block). An undefined
 * kb_context is indistinguishable from the pre-task-22 state as far as the
 * draft prompt is concerned (the field was always optional).
 *
 * @param db            - Drizzle database instance.
 * @param tenantId      - Tenant scope (entries from other tenants are excluded).
 * @param queryText     - The search text (brain_instruction + ": " + action_type).
 * @param kbRef         - Optional explicit entry title from the compiled step.
 *                        If provided, that entry is always included.
 * @param maxResults    - Max entries to return (default KB_MAX_RESULTS).
 * @param similarityFloor - Min cosine similarity (default KB_SIMILARITY_FLOOR).
 * @returns Formatted string for DraftPromptContext.kb_context, or undefined if
 *          no relevant entries are found.
 */
export async function buildKbContextSection(
  db: Db,
  tenantId: string,
  queryText: string,
  kbRef?: string,
  maxResults: number = KB_MAX_RESULTS,
  similarityFloor: number = KB_SIMILARITY_FLOOR,
): Promise<string | undefined> {
  // 1. Resolve the explicit kb_ref entry (if any).
  let pinnedEntry: KbEntry | undefined;
  if (kbRef) {
    pinnedEntry = await fetchByTitle(db, tenantId, kbRef);
    if (!pinnedEntry) {
      console.warn(
        `[context-kb] kb_ref "${kbRef}" not found among active entries for ` +
          `tenant ${tenantId}. Filling all ${maxResults} slots by search.`,
      );
    }
  }

  // If we have a pinned entry, exclude it from search results to avoid
  // duplicates and fill (maxResults - 1) slots. If no pinned entry, fill all.
  const slots = maxResults - (pinnedEntry ? 1 : 0);
  const excludeId = pinnedEntry?.id ?? null;

  let found: KbEntry[] = [];
  if (slots > 0) {
    const semantic = await semanticSearch(db, tenantId, queryText, slots, similarityFloor, excludeId);
    found = semantic ?? (await keywordSearch(db, tenantId, queryText, slots, excludeId));
  }

  // 4. Combine: pinned entry first, then search results.
  const entries: KbEntry[] = [];
  if (pinnedEntry) entries.push(pinnedEntry);
  entries.push(...found);

  if (entries.length === 0) {
    return undefined;
  }

  return formatKbContext(entries);
}

/**
 * Semantic search, or null when it cannot run (no provider, a provider
 * error, a failed query embedding): the caller then falls back to words.
 */
async function semanticSearch(
  db: Db,
  tenantId: string,
  queryText: string,
  limit: number,
  floor: number,
  excludeId: string | null,
): Promise<KbEntry[] | null> {
  const providerResult = await resolveEmbeddingProvider(db, tenantId);
  if (!providerResult.ok) {
    if (!providerResult.notConfigured) {
      console.warn(
        `[context-kb] cannot use semantic search for tenant ${tenantId}: ` +
          `${providerResult.reason}. Falling back to word matching.`,
      );
    }
    return null;
  }

  const { apiKey, baseUrl, embeddingModel, dimensions } = providerResult;
  let queryVector: number[];
  try {
    queryVector = await callEmbedding(baseUrl, apiKey, embeddingModel, queryText, dimensions);
  } catch (err) {
    const msg = err instanceof Error ? err.message : String(err);
    const kind = err instanceof EmbeddingPermanentError ? "permanent" : "transient";
    console.warn(
      `[context-kb] ${kind} error embedding query for tenant ${tenantId}: ` +
        `${msg}. Falling back to word matching.`,
    );
    return null;
  }

  return runSimilaritySearch(db, tenantId, queryVector, limit, floor, excludeId);
}

/** Words that carry no topic; left out of keyword matching. */
const STOP_WORDS = new Set([
  "the", "and", "for", "are", "but", "not", "you", "your", "all", "any", "can",
  "has", "have", "had", "was", "were", "this", "that", "these", "those", "with",
  "from", "into", "about", "they", "them", "their", "our", "out", "its", "who",
  "what", "when", "where", "which", "how", "why", "will", "would", "should",
  "could", "may", "than", "then", "also", "just", "more", "most", "some",
  "such", "only", "own", "same", "very", "each", "other", "been", "being",
  "does", "did", "doing", "here", "there", "over", "under", "again", "once",
]);

/** Distinct lower-case words of 3+ characters, stop words removed. */
export function keywordSet(text: string): Set<string> {
  return new Set(
    text
      .toLowerCase()
      .split(/[^a-z0-9]+/)
      .filter((w) => w.length > 2 && !STOP_WORDS.has(w)),
  );
}

/**
 * Word-matching search over the tenant's active entries (embedded or not):
 * entries sharing at least KB_KEYWORD_MIN_SHARED_WORDS query words, most
 * shared first, ties to the oldest. The same on both backends.
 */
async function keywordSearch(
  db: Db,
  tenantId: string,
  queryText: string,
  limit: number,
  excludeId: string | null,
): Promise<KbEntry[]> {
  const query = keywordSet(queryText);
  if (query.size === 0) return [];
  const rows = await storeFor(db).workerContextKb.listActiveEntries({
    tenantId,
    limit: KB_KEYWORD_SCAN_LIMIT,
    excludeId,
  });
  const scored = rows
    .map((row, index) => {
      const words = keywordSet(`${row.title} ${row.content}`);
      let shared = 0;
      for (const w of query) if (words.has(w)) shared++;
      return { row, shared, index };
    })
    .filter((x) => x.shared >= KB_KEYWORD_MIN_SHARED_WORDS)
    .sort((a, b) => b.shared - a.shared || a.index - b.index)
    .slice(0, limit);

  if (scored.length > 0) {
    console.info(
      `[context-kb] keyword search tenant=${tenantId} ` +
        `accepted=[${scored.map((x) => `"${x.row.title}" (${x.shared})`).join(", ")}]`,
    );
  }
  return scored.map((x) => ({ id: x.row.id, title: x.row.title, content: x.row.content }));
}

// ---------------------------------------------------------------------------
// Internal types and helpers
// ---------------------------------------------------------------------------

interface KbEntry {
  id: string;
  title: string;
  content: string;
}

/**
 * Fetch an active KB entry by exact title for a tenant, embedded or not.
 */
async function fetchByTitle(
  db: Db,
  tenantId: string,
  title: string,
): Promise<KbEntry | undefined> {
  const entry = await storeFor(db).workerContextKb.findActiveEntryByTitle({ tenantId, title });
  return entry ?? undefined;
}

/**
 * Run cosine similarity search using pgvector.
 *
 * The query vector is passed as a Postgres array literal (pgvector format).
 * Uses the <=> (cosine distance) operator; similarity = 1 - distance.
 *
 * Only active entries with a non-NULL embedding are searched.
 * Entries belonging to other tenants are excluded by the WHERE clause.
 *
 * Similarity scores are logged at info level for calibration visibility.
 * Both accepted and rejected candidates are logged so the floor threshold
 * can be tuned against real data.
 */
async function runSimilaritySearch(
  db: Db,
  tenantId: string,
  queryVector: number[],
  limit: number,
  floor: number,
  excludeId: string | null,
): Promise<KbEntry[]> {
  // Fetch top candidates + a few more for logging rejected ones.
  // We fetch (limit + 3) to be able to log the next few below the floor.
  const fetchLimit = limit + 3;

  // pgvector cosine search (1 - distance), tenant-scoped, active and
  // embedded entries only, closest first.
  const rows = await storeFor(db).workerContextKb.searchSimilarEntries({
    tenantId,
    queryVector,
    limit: fetchLimit,
    excludeId,
  });

  const accepted: KbEntry[] = [];
  const rejected: Array<{ title: string; similarity: number }> = [];

  for (const row of rows) {
    const similarity = parseFloat(row.similarity);
    if (similarity >= floor) {
      if (accepted.length < limit) {
        accepted.push({ id: row.id, title: row.title, content: row.content });
      }
    } else {
      rejected.push({ title: row.title, similarity });
    }
  }

  // Log similarity scores for calibration.
  if (accepted.length > 0 || rejected.length > 0) {
    const acceptedLog = accepted
      .map((e) => `"${e.title}"`)
      .join(", ");
    const rejectedLog = rejected
      .map((r) => `"${r.title}" (${r.similarity.toFixed(3)})`)
      .join(", ");

    console.info(
      `[context-kb] similarity search tenant=${tenantId} ` +
        `floor=${floor} ` +
        (accepted.length > 0 ? `accepted=[${acceptedLog}] ` : "accepted=[] ") +
        (rejected.length > 0 ? `below-floor=[${rejectedLog}]` : "below-floor=[]"),
    );
  }

  return accepted;
}

/**
 * Format KB entries into the kb_context string injected into the draft prompt.
 *
 * Format: one entry per block, title as a header, content as the body.
 * Multiple entries are separated by a blank line. This format is compact and
 * readable both by the LLM and by humans inspecting logs.
 */
function formatKbContext(entries: KbEntry[]): string {
  return entries
    .map((e) => `[${e.title}]\n${e.content}`)
    .join("\n\n");
}
